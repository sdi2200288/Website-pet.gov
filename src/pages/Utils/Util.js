export function formatNumber(num) {
  if (num >= 1_000_000) return (num / 1_000_000).toFixed(1) + "M";
  if (num >= 1_000) return (num / 1_000).toFixed(1) + "K";
  return num.toString();
}

export function calculateMO(score,num) {
  if (num === 0) return "0.0";
  return (score / num).toFixed(1);
}

